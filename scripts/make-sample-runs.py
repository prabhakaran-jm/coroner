#!/usr/bin/env python3
"""Generate three SYNTHETIC Coroner runs (A, B, C) for the Viewer.

The runs are invented. They are NOT real Docker experimental evidence: no container ran, nothing was
measured, and every value (ids, times, memory, exit codes) is written by this script. They exist so that
a judge can start the Viewer and see every page without Docker and without the author's saved runs.

    python scripts/make-sample-runs.py --out <empty or new directory>
    python -m coroner.viewer --runs-dir <that directory> --host 127.0.0.1 --port 8765

Output (the same bytes on every run of the same script):

    <out>/README-SYNTHETIC.txt
    <out>/a-20260101T000000Z-sample01/{manifest.json,evidence.jsonl,docker_inspect.json}
    <out>/b-20260101T000100Z-sample02/{...}   ExitCode 137, OOMKilled false, Runner SIGKILL record
    <out>/c-20260101T000200Z-sample03/{...}   ExitCode 137, OOMKilled true, RSS above the 128 MiB limit

Safety:
  * --out is required. There is no default and no overwrite option.
  * The target must not exist or must be an empty directory. Files are opened exclusively (mode "xb").
  * The repository's runs/ directory, anything inside it, and <cwd>/runs are refused, after resolving
    symlinks and junctions. A target that is itself a symlink or junction is refused.
  * Nothing else is read or written. No network, no Docker, no randomness, no clock.

Standard library only. It imports nothing from `tests/` or from `coroner/`; the file formats are
re-implemented here to match the M0 manifest, the Collector evidence envelope and `docker inspect`.
Exit codes: 0 written, 2 refused or failed (nothing is left behind except what existed before).
"""
