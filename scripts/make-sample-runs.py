def build_run_files(key: str) -> dict[str, bytes]:
    """The three files of one run, as bytes. Pure and deterministic."""
    spec = _RUNS[key]
    sch = _schedule(key, spec)
    evidence, count = _evidence(key, spec, sch)
    return {
        "manifest.json": _manifest(key, spec, sch, count),
        "evidence.jsonl": evidence,
        "docker_inspect.json": _inspect(key, spec, sch),
    }


def run_ids() -> dict[str, str]:
    return {key: spec["id"] for key, spec in _RUNS.items()}


# ---------------------------------------------------------------- writing


def _write_new(path: Path, data: bytes) -> None:
    with open(path, "xb") as handle:  # exclusive: never replaces an existing file
        handle.write(data)


def generate(out: str | os.PathLike[str]) -> Path:
    """Write the three runs and the README into `out` (new or empty). Returns the resolved directory."""
    target = check_output_dir(out)
    target.mkdir(parents=True, exist_ok=True)
    created_files: list[Path] = []
    created_dirs: list[Path] = []
    try:
        _write_new(target / README_NAME, README_TEXT.encode("utf-8"))
        created_files.append(target / README_NAME)
        for key in _RUNS:
            run_dir = target / _RUNS[key]["id"]
            run_dir.mkdir(parents=False, exist_ok=False)
            created_dirs.append(run_dir)
            for name, data in build_run_files(key).items():
                _write_new(run_dir / name, data)
                created_files.append(run_dir / name)
    except BaseException:
        for file in reversed(created_files):  # remove only what this call created
            try:
                file.unlink()
            except OSError:
                pass
        for directory in reversed(created_dirs):
            try:
                directory.rmdir()
            except OSError:
                pass
        raise
    return target


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="make-sample-runs.py",
        description="Write three SYNTHETIC Coroner runs (A, B, C) for the Viewer. Not real Docker evidence.",
    )
    parser.add_argument("--out", required=True, help="new or empty directory to write into (never runs/)")
    args = parser.parse_args(argv)
    try:
        target = generate(args.out)
    except RefusedError as exc:
        print(f"make-sample-runs: {exc}", file=sys.stderr)
        return 2
    except OSError as exc:
        print(f"make-sample-runs: could not write the sample runs: {exc}", file=sys.stderr)
        return 2
    print("SYNTHETIC sample runs written (not real Docker evidence):")
    for run_id in run_ids().values():
        print(f"  {run_id}")
    print(f"directory: {target}")
    print(f'next: python -m coroner.viewer --runs-dir "{target}" --host 127.0.0.1 --port 8765')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
